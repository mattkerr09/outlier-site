#!/usr/bin/env python3
"""Write data/binary-requirements.json from the INSTALLED Outlier bundle: the oldest macOS every binary in it can load on.

dyld refuses any Mach-O whose minos (its LC_BUILD_VERSION minimum) is newer than the running macOS, so the bundle's
floor is the highest minos of any file in it. macos_floor_gate.py holds every "macOS N or later" sentence on the site to
this number. It is measured, never typed: this script reads every Mach-O in the bundle with otool.

2026-10-21: data/binary-requirements.json said "GENERATED by scripts/binary_requirements.py", and no such script was in
this repo or the app's; this is it, written for 1.11.952 (the macOS 15 floor) to the file's own schema.

    python3 scripts/binary_requirements.py [/Applications/Outlier.app]
"""
from __future__ import annotations

import collections
import datetime as dt
import json
import os
import pathlib
import plistlib
import re
import subprocess
import sys

MAGIC = (b"\xcf\xfa\xed\xfe", b"\xca\xfe\xba\xbe", b"\xce\xfa\xed\xfe")
OUT = pathlib.Path(__file__).resolve().parent.parent / "data" / "binary-requirements.json"


def minos(path: str):
    out = subprocess.run(["otool", "-l", path], capture_output=True, text=True).stdout
    vals = re.findall(r"minos (\d+(?:\.\d+)*)", out) or re.findall(r"LC_VERSION_MIN_MACOSX\s+cmdsize \d+\s+version (\S+)", out)
    if not vals:
        return None
    best = max(tuple(int(x) for x in v.split(".")) for v in vals)
    return f"{best[0]}.{best[1] if len(best) > 1 else 0}"


def main(app: str) -> int:
    if not os.path.isdir(app):
        print(f"no bundle at {app}"); return 1
    hist, n = collections.Counter(), 0
    for root, _dirs, files in os.walk(app):
        for f in files:
            p = os.path.join(root, f)
            if os.path.islink(p) or not os.path.isfile(p):
                continue
            with open(p, "rb") as fh:
                if fh.read(4) not in MAGIC:
                    continue
            n += 1
            m = minos(p)
            if m:
                hist[m] += 1
    if not n or not hist:
        print("FAIL: no Mach-O with a minos found; refusing to write a floor"); return 1
    floor = max(hist, key=lambda v: tuple(int(x) for x in v.split(".")))
    info = plistlib.load(open(os.path.join(app, "Contents", "Info.plist"), "rb"))
    data = {
        "_note": "GENERATED by scripts/binary_requirements.py from the INSTALLED bundle — do not edit by hand.",
        "product": "Outlier",
        "bundle": app,
        "bundle_version": info.get("CFBundleShortVersionString"),
        "min_macos": floor,
        "mach_o_files": n,
        "minos_histogram": dict(sorted(hist.items(), key=lambda kv: tuple(int(x) for x in kv[0].split(".")))),
        "why": "dyld refuses to load any Mach-O whose minos is newer than the running macOS. The site must never "
               "promise a lower macOS than this number.",
        "measured_at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    OUT.write_text(json.dumps(data, indent=2) + "\n")
    print(f"{data['bundle_version']}: {n} Mach-O, floor macOS {floor} ({data['minos_histogram']}) -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1] if len(sys.argv) > 1 else "/Applications/Outlier.app"))
